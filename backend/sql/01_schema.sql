CREATE FUNCTION tass_config_valid(j JSONB,total_seconds INTEGER) RETURNS BOOLEAN
LANGUAGE plpgsql IMMUTABLE AS $$
DECLARE b JSONB; s JSONB; last_year NUMERIC := -1; last_penalty NUMERIC := 2147483647;
        stage_sum NUMERIC := 0; stage_count INTEGER := 0;
BEGIN
 IF j IS NULL OR jsonb_typeof(j) IS DISTINCT FROM 'object' OR j->>'contract_version' IS DISTINCT FROM '1'
 OR j->'objective_order' IS DISTINCT FROM '["Z","L1","M","experience","change"]'::jsonb
 OR j->>'coverage_mode' IS DISTINCT FROM 'COMPONENTS' OR j->>'load_basis' IS DISTINCT FROM 'T-B'
 OR j->>'lock_policy' IS DISTINCT FROM 'KEEP_LOCKED' OR j->>'unassigned_policy' IS DISTINCT FROM 'DRAFT_ONLY'
 OR j#>>'{experience,beta}' IS DISTINCT FROM '1' OR total_seconds NOT BETWEEN 30 AND 60
 OR jsonb_typeof(j->'stage_budgets')<>'array' OR jsonb_array_length(j->'stage_budgets')<>5
 OR jsonb_typeof(j#>'{experience,penalty_bands}')<>'array'
 OR jsonb_array_length(j#>'{experience,penalty_bands}')=0
 OR j#>>'{experience,unknown_policy}' IS NULL OR j#>>'{experience,unknown_policy}' NOT IN ('BLOCK','PENALTY')
 OR (j#>>'{experience,grade_weights,other}')::NUMERIC <= 0
 OR (j#>>'{experience,grade_weights,9}')::NUMERIC <= (j#>>'{experience,grade_weights,other}')::NUMERIC
 OR (j#>>'{experience,grade_weights,12}')::NUMERIC <= (j#>>'{experience,grade_weights,other}')::NUMERIC
 OR NOT ((j#>>'{experience,as_of_date}')::DATE IS NOT NULL)
 THEN RETURN FALSE; END IF;
 -- Required keys: SQL NULL is not a successful validation result.
 IF NOT (j ?& ARRAY['contract_version','objective_order','coverage_mode','load_basis','lock_policy',
 'unassigned_policy','experience','stage_budgets','non_solver_budget_seconds'])
 OR NOT ((j->'experience') ?& ARRAY['beta','grade_weights','unknown_policy','as_of_date','penalty_bands'])
 OR NOT ((j#>'{experience,grade_weights}') ?& ARRAY['9','12','other']) THEN RETURN FALSE; END IF;
 FOR s IN SELECT value FROM jsonb_array_elements(j->'stage_budgets') LOOP
  IF NOT (s ?& ARRAY['name','seconds']) OR jsonb_typeof(s->'seconds') IS DISTINCT FROM 'number'
  OR s->>'name' IS DISTINCT FROM (j->'objective_order'->>stage_count)
  OR (s->>'seconds')::NUMERIC <= 0 THEN RETURN FALSE; END IF;
  stage_count:=stage_count+1; stage_sum:=stage_sum+(s->>'seconds')::NUMERIC;
 END LOOP;
 IF jsonb_typeof(j->'non_solver_budget_seconds') IS DISTINCT FROM 'number' OR (j->>'non_solver_budget_seconds')::NUMERIC<0
 OR stage_sum+(j->>'non_solver_budget_seconds')::NUMERIC>total_seconds THEN RETURN FALSE; END IF;
 FOR b IN SELECT value FROM jsonb_array_elements(j#>'{experience,penalty_bands}') LOOP
  IF NOT (b ?& ARRAY['min_years','penalty']) OR jsonb_typeof(b->'min_years') IS DISTINCT FROM 'number'
  OR jsonb_typeof(b->'penalty') IS DISTINCT FROM 'number'
  OR (b->>'min_years')::NUMERIC <= last_year
  OR (b->>'min_years')::NUMERIC < 0
  OR (b->>'penalty')::NUMERIC < 0
  OR (b->>'penalty')::NUMERIC <> trunc((b->>'penalty')::NUMERIC)
  OR (b->>'penalty')::NUMERIC > last_penalty THEN RETURN FALSE; END IF;
  IF last_year=-1 AND (b->>'min_years')::NUMERIC<>0 THEN RETURN FALSE; END IF;
  last_year:=(b->>'min_years')::NUMERIC; last_penalty:=(b->>'penalty')::NUMERIC;
 END LOOP;
 IF j#>>'{experience,unknown_policy}'='PENALTY' AND
 (NOT ((j->'experience') ? 'unknown_penalty') OR
 (j#>>'{experience,unknown_penalty}')::NUMERIC<0 OR
 (j#>>'{experience,unknown_penalty}')::NUMERIC<>trunc((j#>>'{experience,unknown_penalty}')::NUMERIC)) THEN RETURN FALSE; END IF;
 IF EXISTS (SELECT 1 FROM jsonb_each_text(j#>'{experience,grade_weights}') w
 WHERE w.value IS NULL OR w.value::numeric<>trunc(w.value::numeric) OR w.value::numeric<=0) THEN RETURN FALSE; END IF;
 IF EXISTS(SELECT 1 FROM jsonb_each(j#>'{experience,grade_weights}') w WHERE jsonb_typeof(w.value) IS DISTINCT FROM 'number') THEN RETURN FALSE; END IF;
 RETURN TRUE;
EXCEPTION WHEN OTHERS THEN RETURN FALSE;
END;
$$;
