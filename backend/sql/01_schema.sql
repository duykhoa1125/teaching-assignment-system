-- Không có trigger TRUNCATE: tài khoản ứng dụng không nên có quyền TRUNCATE/DDL.
CREATE FUNCTION tass_reject_history_mutation() RETURNS TRIGGER
LANGUAGE plpgsql AS $$
BEGIN
    RAISE EXCEPTION '% is append-only; % is not allowed', TG_TABLE_NAME, TG_OP
        USING ERRCODE = '23514';
    RETURN NULL;
END;
$$;

