CREATE FUNCTION tass_check_snapshot() RETURNS TRIGGER LANGUAGE plpgsql AS $$
DECLARE key TEXT; expected_token TEXT;
BEGIN
 SELECT source_revision_token INTO expected_token FROM assignment_round WHERE id=NEW.round_id FOR SHARE;
 IF NEW.source_revision_token IS DISTINCT FROM expected_token
 OR NEW.snapshot_schema_version<>2 OR NEW.payload_json->>'schema_version' IS DISTINCT FROM '2'
 OR NEW.payload_json->>'source_revision_token' IS DISTINCT FROM NEW.source_revision_token
 OR NEW.content_hash IS DISTINCT FROM md5(NEW.payload_json::TEXT)
 OR (NEW.payload_json#>>'{round,id}')::BIGINT IS DISTINCT FROM NEW.round_id
 OR (NEW.payload_json#>>'{optimization_config,id}')::BIGINT IS DISTINCT FROM NEW.optimization_config_id
 OR (NEW.payload_json#>>'{rule_set,id}')::BIGINT IS DISTINCT FROM NEW.rule_set_version_id THEN
  RAISE EXCEPTION 'Invalid snapshot identity/token/contract/checksum' USING ERRCODE='23514'; END IF;
 FOREACH key IN ARRAY ARRAY['teachers','classes','subjects','scope','applicability','required_components','demands',
  'employment','qualifications','experience','experience_penalties','workload_basis','duties','reductions',
  'converted_activities','calculation_periods','period_workloads','locked_assignments','rules'] LOOP
  IF jsonb_typeof(NEW.payload_json->key) IS DISTINCT FROM 'array' THEN
   RAISE EXCEPTION 'Snapshot is missing array %',key USING ERRCODE='23514'; END IF;
 END LOOP;
 RETURN NEW;
END;
$$;
CREATE TRIGGER a_snapshot_contract BEFORE INSERT ON input_snapshot FOR EACH ROW EXECUTE FUNCTION tass_check_snapshot();

CREATE FUNCTION tass_guard_export() RETURNS TRIGGER LANGUAGE plpgsql AS $$
DECLARE v plan_version%ROWTYPE; p assignment_plan%ROWTYPE;
BEGIN
 SELECT ap.* INTO p FROM assignment_plan ap JOIN plan_version pv ON pv.plan_id=ap.id WHERE pv.id=NEW.plan_version_id FOR UPDATE OF ap;
 SELECT * INTO v FROM plan_version WHERE id=NEW.plan_version_id FOR UPDATE;
 IF p.current_version_id IS DISTINCT FROM v.id OR v.status<>'READY_TO_EXPORT'
 OR NEW.revision_no<>v.revision_no OR NEW.input_snapshot_id<>v.input_snapshot_id
 OR NOT COALESCE(tass_validation_is_fresh(NEW.validation_run_id),FALSE)
 OR NOT EXISTS(SELECT 1 FROM validation_run vr WHERE vr.id=NEW.validation_run_id
  AND vr.plan_version_id=v.id AND vr.revision_no=NEW.revision_no AND vr.input_snapshot_id=NEW.input_snapshot_id
  AND vr.source_revision_token=NEW.source_revision_token AND vr.overall_status<>'VIOLATION')
 OR EXISTS(SELECT 1 FROM feedback WHERE plan_id=p.id AND status='PENDING')
 OR NULLIF(btrim(NEW.file_ref),'') IS NULL OR NULLIF(btrim(NEW.content_hash),'') IS NULL THEN
  RAISE EXCEPTION 'Export requires current READY_TO_EXPORT, fresh matching validation and saved file metadata' USING ERRCODE='23514'; END IF;
 RETURN NEW;
END;
$$;
CREATE TRIGGER a_export_guard BEFORE INSERT ON export_record FOR EACH ROW EXECUTE FUNCTION tass_guard_export();

