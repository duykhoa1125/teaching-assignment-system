CREATE FUNCTION tass_solver_summary_valid(j JSONB) RETURNS BOOLEAN
LANGUAGE plpgsql IMMUTABLE AS $$
DECLARE s JSONB; n INTEGER:=0;
BEGIN
 IF j IS NULL THEN RETURN TRUE; END IF; -- a pending run has no result yet
 IF jsonb_typeof(j) IS DISTINCT FROM 'object' OR NOT (j ?& ARRAY['contract_version','ortools_version','random_seed',
 'num_workers','total_budget_seconds','stages','cp_sat_status','termination_reason','apply_outcome','demo_only','config_hash','coverage'])
 OR j->>'contract_version' IS DISTINCT FROM '1' OR jsonb_typeof(j->'stages')<>'array'
 OR jsonb_array_length(j->'stages')<>5 OR jsonb_typeof(j->'demo_only') IS DISTINCT FROM 'boolean'
 OR jsonb_typeof(j->'num_workers') IS DISTINCT FROM 'number' OR (j->>'num_workers')::NUMERIC<1
 OR (j->>'num_workers')::NUMERIC<>trunc((j->>'num_workers')::NUMERIC)
 OR jsonb_typeof(j->'coverage') IS DISTINCT FROM 'object'
 OR NULLIF(j->>'config_hash','') IS NULL THEN RETURN FALSE; END IF;
 FOR s IN SELECT value FROM jsonb_array_elements(j->'stages') LOOP
  IF s->>'name' IS DISTINCT FROM ('["Z","L1","M","experience","change"]'::jsonb->>n)
  OR NOT (s ?& ARRAY['status','objective','best_bound','elapsed_ms','stop_reason','exactOptimalityProven','gap_tolerance'])
  OR s->>'status' IS NULL OR s->>'status' NOT IN ('NOT_RUN','OPTIMAL','FEASIBLE','INFEASIBLE','UNKNOWN','MODEL_INVALID')
  OR jsonb_typeof(s->'elapsed_ms') IS DISTINCT FROM 'number' OR (s->>'elapsed_ms')::NUMERIC<0
  OR jsonb_typeof(s->'gap_tolerance') IS DISTINCT FROM 'number' OR (s->>'gap_tolerance')::NUMERIC<0
  OR jsonb_typeof(s->'exactOptimalityProven') IS DISTINCT FROM 'boolean'
  OR ((s->>'exactOptimalityProven')::BOOLEAN AND (s->>'status'<>'OPTIMAL'
    OR s->>'objective' IS NULL OR s->>'best_bound' IS NULL
    OR (s->>'gap_tolerance')::NUMERIC<>0
    OR (s->>'objective')::NUMERIC<>(s->>'best_bound')::NUMERIC)) THEN RETURN FALSE; END IF;
  n:=n+1;
 END LOOP;
 IF (j->>'demo_only')::BOOLEAN AND EXISTS (SELECT 1 FROM jsonb_array_elements(j->'stages') z
 WHERE z->>'status'<>'NOT_RUN' OR (z->>'exactOptimalityProven')::BOOLEAN) THEN RETURN FALSE; END IF;
 RETURN TRUE;
EXCEPTION WHEN OTHERS THEN RETURN FALSE;
END;
$$;
