-- Chan sua khoa ngu canh o bang cha khi da co con. Ten/metadata van sua duoc:
-- chung se lam source token cu het han. Thay doi co cau can migration co doi soat.
CREATE FUNCTION tass_guard_parent_context() RETURNS TRIGGER LANGUAGE plpgsql AS $$
DECLARE cols TEXT[]; k TEXT; changed BOOLEAN:=FALSE; referenced BOOLEAN; f RECORD;
BEGIN
 cols:=string_to_array(TG_ARGV[0],',');
 FOREACH k IN ARRAY cols LOOP
  IF to_jsonb(OLD)->k IS DISTINCT FROM to_jsonb(NEW)->k THEN changed:=TRUE; END IF;
 END LOOP;
 IF NOT changed THEN RETURN NEW; END IF;
 FOR f IN
  SELECT conrelid::regclass AS child, a.attname AS child_col
  FROM pg_constraint con JOIN LATERAL unnest(con.conkey,con.confkey) pair(childkey,parentkey) ON TRUE
  JOIN pg_attribute a ON a.attrelid=con.conrelid AND a.attnum=pair.childkey
  JOIN pg_attribute pa ON pa.attrelid=con.confrelid AND pa.attnum=pair.parentkey
  WHERE con.contype='f' AND con.confrelid=TG_RELID AND pa.attname='id'
 LOOP
  EXECUTE format('SELECT EXISTS(SELECT 1 FROM %s WHERE %I=$1)',f.child,f.child_col) INTO referenced USING OLD.id;
  IF referenced THEN RAISE EXCEPTION 'Referenced context of % id=% is protected; migrate dependents explicitly',TG_TABLE_NAME,OLD.id USING ERRCODE='23514'; END IF;
 END LOOP;
 RETURN NEW;
END;
$$;
