-- 15. teaching_experience
CREATE TABLE teaching_experience (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    teacher_id BIGINT NOT NULL,
    subject_id BIGINT NOT NULL,
    grade_id BIGINT NOT NULL,
    recorded_by BIGINT NOT NULL,
    recorded_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    experience_status VARCHAR(30) NOT NULL CHECK (experience_status IN ('HAS_EXPERIENCE','NO_EXPERIENCE','UNKNOWN')),
    years_of_experience NUMERIC CHECK (years_of_experience >= 0 AND years_of_experience < 1000),
    as_of_date DATE NOT NULL,
    evidence_ref TEXT,
    source_import_id BIGINT,
    verified_by BIGINT,
    verified_at TIMESTAMPTZ,
    UNIQUE (teacher_id, subject_id, grade_id, as_of_date),
    CHECK ((experience_status = 'UNKNOWN' AND years_of_experience IS NULL) OR (experience_status = 'NO_EXPERIENCE' AND years_of_experience IS NOT NULL AND years_of_experience = 0) OR (experience_status = 'HAS_EXPERIENCE' AND years_of_experience IS NOT NULL AND years_of_experience > 0)),
    CHECK (experience_status = 'UNKNOWN' OR (verified_by IS NOT NULL AND verified_at IS NOT NULL AND NULLIF(btrim(evidence_ref),'') IS NOT NULL))
);

