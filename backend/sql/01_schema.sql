-- 25. assignment_plan
CREATE TABLE assignment_plan (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    round_id BIGINT NOT NULL REFERENCES assignment_round(id),
    plan_code VARCHAR(80) NOT NULL,
    current_version_id BIGINT,
    created_by BIGINT NOT NULL REFERENCES user_account(id),
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    UNIQUE (round_id),
    UNIQUE (plan_code),
    UNIQUE (current_version_id)
);

-- 26. plan_version
CREATE TABLE plan_version (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    plan_id BIGINT NOT NULL REFERENCES assignment_plan(id),
    version_no INTEGER NOT NULL CHECK (version_no > 0),
    source_version_id BIGINT,
    status VARCHAR(30) NOT NULL DEFAULT 'DRAFT' CHECK (status IN ('DRAFT','OPEN_FOR_FEEDBACK','FEEDBACK_PROCESSING','READY_TO_EXPORT','EXPORTED')),
    revision_no BIGINT NOT NULL DEFAULT 0 CHECK (revision_no >= 0),
    input_snapshot_id BIGINT NOT NULL REFERENCES input_snapshot(id),
    feedback_deadline TIMESTAMPTZ,
    skip_reopen_reason TEXT,
    created_by BIGINT NOT NULL REFERENCES user_account(id),
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    UNIQUE (plan_id, version_no),
    UNIQUE (id, plan_id),
    UNIQUE (id, input_snapshot_id),
    CHECK (source_version_id IS NULL OR source_version_id <> id),
    FOREIGN KEY (source_version_id, plan_id) REFERENCES plan_version(id, plan_id)
);

-- 27. plan_demand
CREATE TABLE plan_demand (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    plan_version_id BIGINT NOT NULL REFERENCES plan_version(id),
    demand_id BIGINT NOT NULL REFERENCES teaching_demand(id),
    periods_per_week_snapshot NUMERIC(5,2) NOT NULL CHECK (periods_per_week_snapshot > 0),
    teacher_id BIGINT REFERENCES teacher(id),
    unassigned_reason_code VARCHAR(80),
    unassigned_reason_text TEXT,
    UNIQUE (plan_version_id, demand_id),
    UNIQUE (id, plan_version_id, teacher_id),
    CHECK ((teacher_id IS NULL AND NULLIF(btrim(unassigned_reason_code),'') IS NOT NULL) OR (teacher_id IS NOT NULL AND unassigned_reason_code IS NULL AND unassigned_reason_text IS NULL))
);

-- 28. feedback
CREATE TABLE feedback (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    plan_version_id BIGINT NOT NULL REFERENCES plan_version(id),
    teacher_id BIGINT NOT NULL REFERENCES teacher(id),
    plan_demand_id BIGINT,
    feedback_type VARCHAR(50) NOT NULL CHECK (btrim(feedback_type) <> ''),
    subject_id BIGINT REFERENCES subject(id),
    requested_periods_per_week NUMERIC(5,2) CHECK (requested_periods_per_week > 0),
    content TEXT NOT NULL CHECK (btrim(content) <> ''),
    submitted_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    status VARCHAR(40) NOT NULL CHECK (btrim(status) <> ''),
    resolution TEXT,
    handled_by BIGINT REFERENCES user_account(id),
    handled_at TIMESTAMPTZ,
    resulting_version_id BIGINT REFERENCES plan_version(id),
    FOREIGN KEY (plan_demand_id, plan_version_id, teacher_id) REFERENCES plan_demand(id, plan_version_id, teacher_id),
    CHECK (handled_at IS NULL OR handled_at >= submitted_at),
    CHECK (requested_periods_per_week IS NULL OR subject_id IS NOT NULL)
);

-- 29. validation_run
CREATE TABLE validation_run (
