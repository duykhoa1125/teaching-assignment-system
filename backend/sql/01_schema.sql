-- 27. plan_demand
CREATE TABLE plan_demand (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    plan_version_id BIGINT NOT NULL,
    demand_id BIGINT NOT NULL,
    periods_per_week_snapshot NUMERIC NOT NULL CHECK (periods_per_week_snapshot > 0 AND periods_per_week_snapshot <= 999.99 AND periods_per_week_snapshot = trunc(periods_per_week_snapshot,2)),
    teacher_id BIGINT,
    unassigned_reason_code VARCHAR(80),
    unassigned_reason_text TEXT,
    UNIQUE (plan_version_id, demand_id),
    UNIQUE (id, plan_version_id, teacher_id),
    is_locked BOOLEAN NOT NULL DEFAULT FALSE,
    locked_by BIGINT,
    locked_at TIMESTAMPTZ,
    lock_reason TEXT,
    CHECK ((teacher_id IS NULL AND NULLIF(btrim(unassigned_reason_code),'') IS NOT NULL AND NULLIF(btrim(unassigned_reason_text),'') IS NOT NULL) OR (teacher_id IS NOT NULL AND unassigned_reason_code IS NULL AND unassigned_reason_text IS NULL)),
    CHECK ((is_locked AND teacher_id IS NOT NULL AND locked_by IS NOT NULL AND locked_at IS NOT NULL AND NULLIF(btrim(lock_reason),'') IS NOT NULL) OR (NOT is_locked AND locked_by IS NULL AND locked_at IS NULL AND lock_reason IS NULL))
);

-- 28. feedback
CREATE TABLE feedback (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    plan_version_id BIGINT NOT NULL,
    teacher_id BIGINT NOT NULL,
    plan_demand_id BIGINT,
    feedback_type VARCHAR(50) NOT NULL CHECK (btrim(feedback_type) <> ''),
    subject_id BIGINT,
    requested_periods_per_week NUMERIC NULL CHECK (requested_periods_per_week > 0 AND requested_periods_per_week <= 999.99 AND requested_periods_per_week = trunc(requested_periods_per_week,2)),
    content TEXT NOT NULL CHECK (btrim(content) <> ''),
    submitted_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    status VARCHAR(40) NOT NULL CHECK (btrim(status) <> ''),
    resolution TEXT,
    handled_by BIGINT,
    handled_at TIMESTAMPTZ,
    resulting_version_id BIGINT,
    CHECK (handled_at IS NULL OR handled_at >= submitted_at),
    CHECK (requested_periods_per_week IS NULL OR subject_id IS NOT NULL),
    plan_id BIGINT NOT NULL,
    CHECK (resulting_version_id IS NULL OR resulting_version_id <> plan_version_id)
);

