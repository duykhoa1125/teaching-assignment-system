    valid_from DATE NOT NULL,
    valid_to DATE NOT NULL,
    unit VARCHAR(30) NOT NULL DEFAULT 'PERIOD_PER_WEEK' CHECK (unit = 'PERIOD_PER_WEEK'),
    CHECK (valid_to >= valid_from),
    UNIQUE (semester_id, class_id, subject_id, demand_type, valid_from, valid_to)
);

