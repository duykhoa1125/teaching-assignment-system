-- 31. solver_run
CREATE TABLE solver_run (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    plan_version_id BIGINT NOT NULL,
    input_snapshot_id BIGINT NOT NULL,
    base_revision_no BIGINT NOT NULL CHECK (base_revision_no >= 0),
    requested_by BIGINT NOT NULL REFERENCES user_account(id),
    started_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    finished_at TIMESTAMPTZ,
    status VARCHAR(40) NOT NULL CHECK (btrim(status) <> ''),
    result_summary_json JSONB,
    applied_revision_no BIGINT CHECK (applied_revision_no >= 0),
    FOREIGN KEY (plan_version_id, input_snapshot_id) REFERENCES plan_version(id, input_snapshot_id),
    CHECK (finished_at IS NULL OR finished_at >= started_at),
    CHECK (applied_revision_no IS NULL OR applied_revision_no > base_revision_no)
);

