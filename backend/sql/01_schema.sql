CREATE FUNCTION tass_guard_feedback() RETURNS TRIGGER LANGUAGE plpgsql AS $$
DECLARE p assignment_plan%ROWTYPE; v plan_version%ROWTYPE;
BEGIN
 IF TG_OP='DELETE' THEN RAISE EXCEPTION 'Submitted feedback cannot be deleted' USING ERRCODE='23514'; END IF;
 SELECT * INTO p FROM assignment_plan WHERE id=NEW.plan_id FOR UPDATE;
 SELECT * INTO v FROM plan_version WHERE id=NEW.plan_version_id FOR UPDATE;
 IF v.plan_id IS DISTINCT FROM p.id OR p.current_version_id IS DISTINCT FROM v.id THEN
  RAISE EXCEPTION 'Feedback source must be current in the same plan' USING ERRCODE='23514'; END IF;
 IF TG_OP='INSERT' THEN
  IF v.status<>'OPEN_FOR_FEEDBACK' OR v.feedback_deadline IS NULL OR clock_timestamp()>v.feedback_deadline THEN
   RAISE EXCEPTION 'Feedback is closed or past deadline' USING ERRCODE='23514'; END IF;
  NEW.submitted_at:=clock_timestamp(); -- never trust backdated client timestamps
  IF NEW.status<>'PENDING' THEN RAISE EXCEPTION 'New feedback starts PENDING' USING ERRCODE='23514'; END IF;
  IF NEW.subject_id IS NOT NULL AND NOT EXISTS(SELECT 1 FROM plan_demand pd
   JOIN input_snapshot sn ON sn.id=v.input_snapshot_id CROSS JOIN LATERAL jsonb_array_elements(sn.payload_json->'demands') z
   WHERE pd.plan_version_id=v.id AND pd.teacher_id=NEW.teacher_id AND (z->>'id')::BIGINT=pd.demand_id
    AND (z->>'subject_id')::BIGINT=NEW.subject_id) THEN
   RAISE EXCEPTION 'Feedback subject must be assigned to this sender in source version' USING ERRCODE='23514'; END IF;
 ELSE
  IF v.status<>'FEEDBACK_PROCESSING' THEN RAISE EXCEPTION 'Only current FEEDBACK_PROCESSING accepts handling updates' USING ERRCODE='23514'; END IF;
  IF (to_jsonb(NEW)-ARRAY['status','resolution','handled_by','handled_at','resulting_version_id'])
    IS DISTINCT FROM (to_jsonb(OLD)-ARRAY['status','resolution','handled_by','handled_at','resulting_version_id']) THEN
   RAISE EXCEPTION 'Submitted feedback content/source/sender is immutable' USING ERRCODE='23514'; END IF;
 END IF;
 IF NEW.resulting_version_id IS NOT NULL AND NOT EXISTS(SELECT 1 FROM plan_version dst
  WHERE dst.id=NEW.resulting_version_id AND dst.plan_id=NEW.plan_id
   AND dst.source_version_id=NEW.plan_version_id AND dst.status='DRAFT' AND dst.version_no>v.version_no) THEN
  RAISE EXCEPTION 'Feedback result must be a new DRAFT from its source in same plan' USING ERRCODE='23514'; END IF;
 RETURN NEW;
END;
$$;
CREATE TRIGGER b_guard_feedback BEFORE INSERT OR UPDATE OR DELETE ON feedback FOR EACH ROW EXECUTE FUNCTION tass_guard_feedback();

