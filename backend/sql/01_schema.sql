    status VARCHAR(30) NOT NULL DEFAULT 'DRAFT' CHECK (status IN ('DRAFT','OPEN_FOR_FEEDBACK','FEEDBACK_PROCESSING','READY_TO_EXPORT','EXPORTED')),
