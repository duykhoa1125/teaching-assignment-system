CREATE FUNCTION tass_validation_is_fresh(p_run BIGINT) RETURNS BOOLEAN LANGUAGE sql STABLE AS $$
 SELECT COALESCE(p.current_version_id=v.id AND vr.revision_no=v.revision_no
 AND vr.input_snapshot_id=v.input_snapshot_id AND vr.source_revision_token=r.source_revision_token
 AND sn.source_revision_token=vr.source_revision_token,FALSE)
 FROM validation_run vr JOIN plan_version v ON v.id=vr.plan_version_id
 JOIN assignment_plan p ON p.id=v.plan_id JOIN assignment_round r ON r.id=p.round_id
 JOIN input_snapshot sn ON sn.id=vr.input_snapshot_id WHERE vr.id=p_run;
$$;

CREATE FUNCTION tass_guard_plan() RETURNS TRIGGER LANGUAGE plpgsql AS $$
DECLARE old_v plan_version%ROWTYPE; new_v plan_version%ROWTYPE;
BEGIN
 IF TG_OP='DELETE' THEN RAISE EXCEPTION 'Plan history cannot be deleted' USING ERRCODE='23514'; END IF;
 IF NEW.round_id<>OLD.round_id OR NEW.created_by<>OLD.created_by OR NEW.created_at<>OLD.created_at THEN
  RAISE EXCEPTION 'Plan identity is immutable' USING ERRCODE='23514'; END IF;
 IF NEW.current_version_id IS DISTINCT FROM OLD.current_version_id THEN
  IF NEW.current_version_id IS NULL THEN RAISE EXCEPTION 'Current version cannot be cleared' USING ERRCODE='23514'; END IF;
  SELECT * INTO new_v FROM plan_version WHERE id=NEW.current_version_id;
  IF new_v.plan_id IS DISTINCT FROM NEW.id OR new_v.status IS DISTINCT FROM 'DRAFT' THEN
   RAISE EXCEPTION 'New current must be a DRAFT in this plan' USING ERRCODE='23514'; END IF;
  IF OLD.current_version_id IS NOT NULL THEN
   SELECT * INTO old_v FROM plan_version WHERE id=OLD.current_version_id;
   IF new_v.version_no<=old_v.version_no THEN RAISE EXCEPTION 'Restore creates a new DRAFT; do not move current backwards' USING ERRCODE='23514'; END IF;
   IF EXISTS(SELECT 1 FROM feedback WHERE plan_version_id=old_v.id AND status='PENDING') THEN
    RAISE EXCEPTION 'Process source feedback before replacing the version' USING ERRCODE='23514'; END IF;
  END IF;
 END IF;
 RETURN NEW;
END;
$$;
CREATE TRIGGER b_guard_plan BEFORE UPDATE OR DELETE ON assignment_plan FOR EACH ROW EXECUTE FUNCTION tass_guard_plan();

CREATE FUNCTION tass_guard_version() RETURNS TRIGGER LANGUAGE plpgsql AS $$
DECLARE p assignment_plan%ROWTYPE; valid_transition BOOLEAN; checked BIGINT;
BEGIN
 SELECT * INTO p FROM assignment_plan WHERE id=OLD.plan_id FOR UPDATE;
 IF TG_OP='DELETE' OR p.current_version_id IS DISTINCT FROM OLD.id THEN
  RAISE EXCEPTION 'Historical version is read-only' USING ERRCODE='23514'; END IF;
 IF ROW(NEW.plan_id,NEW.version_no,NEW.source_version_id,NEW.created_by,NEW.created_at)
  IS DISTINCT FROM ROW(OLD.plan_id,OLD.version_no,OLD.source_version_id,OLD.created_by,OLD.created_at)
  OR NEW.revision_no<OLD.revision_no THEN RAISE EXCEPTION 'Version identity/revision is immutable or monotone' USING ERRCODE='23514'; END IF;
 IF NEW.input_snapshot_id<>OLD.input_snapshot_id AND OLD.status<>'DRAFT' THEN
  RAISE EXCEPTION 'Only current DRAFT may refresh its snapshot' USING ERRCODE='23514'; END IF;
 valid_transition:=NEW.status=OLD.status OR
  (OLD.status='DRAFT' AND NEW.status IN ('OPEN_FOR_FEEDBACK','READY_TO_EXPORT')) OR
  (OLD.status='OPEN_FOR_FEEDBACK' AND NEW.status='FEEDBACK_PROCESSING') OR
  (OLD.status='FEEDBACK_PROCESSING' AND NEW.status='READY_TO_EXPORT') OR
  (OLD.status='READY_TO_EXPORT' AND NEW.status='EXPORTED');
 IF NOT valid_transition THEN RAISE EXCEPTION 'Invalid version transition % -> %',OLD.status,NEW.status USING ERRCODE='23514'; END IF;
 IF NEW.status<>OLD.status AND NEW.status IN ('OPEN_FOR_FEEDBACK','READY_TO_EXPORT') THEN
  SELECT vr.id INTO checked FROM validation_run vr WHERE vr.plan_version_id=OLD.id
    AND tass_validation_is_fresh(vr.id) AND vr.overall_status<>'VIOLATION'
    AND NOT EXISTS(SELECT 1 FROM validation_result x WHERE x.validation_run_id=vr.id AND
     (x.result_status='VIOLATION' OR (x.result_status='INSUFFICIENT_DATA' AND x.calculation_period NOT LIKE 'ACADEMIC_YEAR:%')))
    ORDER BY vr.checked_at DESC,vr.id DESC LIMIT 1;
  IF checked IS NULL OR EXISTS(SELECT 1 FROM v_tass_preparation_issues WHERE round_id=p.round_id)
   OR EXISTS(SELECT 1 FROM v_tass_required_coverage WHERE round_id=p.round_id AND coverage_status<>'ASSIGNED')
   THEN RAISE EXCEPTION 'Opening/export requires fresh checks and complete confirmed components' USING ERRCODE='23514'; END IF;
  IF NEW.status='OPEN_FOR_FEEDBACK' AND (NEW.feedback_deadline IS NULL OR NEW.feedback_deadline<=clock_timestamp()) THEN
   RAISE EXCEPTION 'Feedback deadline must be in the future' USING ERRCODE='23514'; END IF;
  IF NEW.status='READY_TO_EXPORT' AND EXISTS(SELECT 1 FROM feedback f WHERE f.plan_id=NEW.plan_id AND f.status='PENDING') THEN
   RAISE EXCEPTION 'Pending feedback prevents export' USING ERRCODE='23514'; END IF;
 END IF;
 IF NEW.status<>OLD.status AND NEW.status='EXPORTED' AND NOT EXISTS(
  SELECT 1 FROM export_record ex WHERE ex.plan_version_id=OLD.id AND ex.revision_no=OLD.revision_no
   AND ex.input_snapshot_id=OLD.input_snapshot_id
   AND ex.source_revision_token=(SELECT r.source_revision_token FROM assignment_round r WHERE r.id=p.round_id)) THEN
  RAISE EXCEPTION 'Save a verified export record before setting EXPORTED' USING ERRCODE='23514'; END IF;
 IF to_jsonb(NEW) IS DISTINCT FROM to_jsonb(OLD) AND NEW.revision_no=OLD.revision_no THEN NEW.revision_no:=OLD.revision_no+1; END IF;
 RETURN NEW;
END;
$$;
CREATE TRIGGER b_guard_version BEFORE UPDATE OR DELETE ON plan_version FOR EACH ROW EXECUTE FUNCTION tass_guard_version();

CREATE FUNCTION tass_guard_assignment() RETURNS TRIGGER LANGUAGE plpgsql AS $$
DECLARE vid BIGINT; p assignment_plan%ROWTYPE; v plan_version%ROWTYPE; sn input_snapshot%ROWTYPE;
        rr assignment_round%ROWTYPE; src JSONB;
BEGIN
 vid:=CASE WHEN TG_OP='DELETE' THEN OLD.plan_version_id ELSE NEW.plan_version_id END;
 SELECT ap.* INTO p FROM assignment_plan ap JOIN plan_version pv ON pv.plan_id=ap.id WHERE pv.id=vid FOR UPDATE OF ap;
 SELECT * INTO v FROM plan_version WHERE id=vid FOR UPDATE;
 SELECT * INTO sn FROM input_snapshot WHERE id=v.input_snapshot_id;
 SELECT * INTO rr FROM assignment_round WHERE id=p.round_id FOR SHARE;
 IF p.current_version_id IS DISTINCT FROM vid OR v.status<>'DRAFT' THEN
  RAISE EXCEPTION 'Assignments can change only in current DRAFT' USING ERRCODE='23514'; END IF;
 IF sn.source_revision_token IS DISTINCT FROM rr.source_revision_token THEN
  RAISE EXCEPTION 'STALE_INPUT: refresh snapshot before editing' USING ERRCODE='40001'; END IF;
 IF TG_OP='DELETE' THEN
  IF OLD.is_locked THEN RAISE EXCEPTION 'LOCK_CONFLICT: unlock before deletion' USING ERRCODE='23514'; END IF;
  RETURN OLD;
 END IF;
 IF TG_OP='UPDATE' THEN
  IF NEW.plan_version_id<>OLD.plan_version_id OR NEW.demand_id<>OLD.demand_id THEN
   RAISE EXCEPTION 'Assignment identity cannot move' USING ERRCODE='23514'; END IF;
  IF OLD.is_locked AND ROW(NEW.teacher_id,NEW.periods_per_week_snapshot)
     IS DISTINCT FROM ROW(OLD.teacher_id,OLD.periods_per_week_snapshot) THEN
   RAISE EXCEPTION 'LOCK_CONFLICT: unlock in a separate operation before changing assignment' USING ERRCODE='23514'; END IF;
 END IF;
 SELECT z INTO src FROM jsonb_array_elements(sn.payload_json->'demands') z WHERE (z->>'id')::BIGINT=NEW.demand_id;
 IF src IS NULL OR (src->>'periods_per_week')::NUMERIC<>NEW.periods_per_week_snapshot THEN
  RAISE EXCEPTION 'Assignment periods/demand must match captured snapshot' USING ERRCODE='23514'; END IF;
 IF NOT EXISTS(SELECT 1 FROM teaching_demand td JOIN round_subject_scope sc ON sc.subject_id=td.subject_id
   JOIN class_subject_applicability a ON a.scope_id=sc.id AND a.class_id=td.class_id
   WHERE td.id=NEW.demand_id AND td.semester_id=rr.semester_id AND sc.round_id=rr.id
    AND a.status='APPLICABLE' AND td.status='ACTIVE') THEN
  RAISE EXCEPTION 'Demand is outside applicable active scope' USING ERRCODE='23514'; END IF;
 IF NEW.teacher_id IS NOT NULL AND tass_teacher_eligible(NEW.teacher_id,NEW.demand_id) IS DISTINCT FROM TRUE THEN
  RAISE EXCEPTION 'Teacher is ineligible for this school/subject/level/effective interval' USING ERRCODE='23514'; END IF;
 RETURN NEW;
END;
$$;
CREATE TRIGGER b_guard_assignment BEFORE INSERT OR UPDATE OR DELETE ON plan_demand FOR EACH ROW EXECUTE FUNCTION tass_guard_assignment();
