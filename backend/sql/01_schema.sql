CREATE FUNCTION tass_experience_penalty(p_years NUMERIC,p_config JSONB) RETURNS INTEGER LANGUAGE sql IMMUTABLE AS $$
 SELECT CASE WHEN p_years IS NULL THEN CASE WHEN p_config#>>'{experience,unknown_policy}'='PENALTY'
  THEN (p_config#>>'{experience,unknown_penalty}')::INTEGER END
 ELSE (SELECT (b->>'penalty')::INTEGER FROM jsonb_array_elements(p_config#>'{experience,penalty_bands}') b
  WHERE (b->>'min_years')::NUMERIC<=p_years ORDER BY (b->>'min_years')::NUMERIC DESC LIMIT 1) END;
$$;

CREATE FUNCTION tass_capture_snapshot(p_round BIGINT,p_config BIGINT,p_rules BIGINT,
 p_locks JSONB DEFAULT '[]'::JSONB) RETURNS BIGINT LANGUAGE plpgsql AS $$
DECLARE r assignment_round%ROWTYPE; school_key BIGINT; config JSONB; payload JSONB; result_id BIGINT;
BEGIN
 SELECT * INTO STRICT r FROM assignment_round WHERE id=p_round FOR SHARE;
 SELECT y.school_id INTO school_key FROM semester se JOIN academic_year y ON y.id=se.academic_year_id WHERE se.id=r.semester_id;
 SELECT criteria_weights_json INTO STRICT config FROM optimization_config WHERE id=p_config;
 IF jsonb_typeof(p_locks) IS DISTINCT FROM 'array' THEN RAISE EXCEPTION 'Locks snapshot must be an array' USING ERRCODE='23514'; END IF;
 payload:=jsonb_build_object(
 'demo_only',TRUE,'schema_version',2,'source_revision_token',r.source_revision_token,
 'school',(SELECT to_jsonb(x) FROM school x WHERE x.id=school_key),
