    semester_id BIGINT NOT NULL,
    class_id BIGINT NOT NULL,
    subject_id BIGINT NOT NULL,
    periods_per_week NUMERIC NOT NULL CHECK (periods_per_week > 0 AND periods_per_week <= 999.99 AND periods_per_week = trunc(periods_per_week,2)),
