-- 19. class_subject_applicability
CREATE TABLE class_subject_applicability (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    scope_id BIGINT NOT NULL REFERENCES round_subject_scope(id),
    class_id BIGINT NOT NULL REFERENCES school_class(id),
    status VARCHAR(30) NOT NULL CHECK (status IN ('APPLICABLE','NOT_APPLICABLE','UNDETERMINED')),
    reason TEXT,
    updated_by BIGINT NOT NULL REFERENCES user_account(id),
