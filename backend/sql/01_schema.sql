-- Kiểm tra ngữ cảnh cơ bản khi INSERT/UPDATE bản ghi con.
-- Quy tắc nghiệp vụ nhiều bảng còn lại được liệt kê ở đầu file.
CREATE FUNCTION tass_check_context() RETURNS TRIGGER
LANGUAGE plpgsql AS $$
DECLARE
    context_ok BOOLEAN;
BEGIN
    CASE TG_TABLE_NAME
    WHEN 'semester' THEN
        SELECT NEW.starts_on >= y.starts_on AND NEW.ends_on <= y.ends_on
        INTO context_ok FROM academic_year y WHERE y.id = NEW.academic_year_id;
    WHEN 'user_account' THEN
        IF NEW.teacher_id IS NULL THEN RETURN NEW; END IF;
        SELECT t.school_id = NEW.school_id INTO context_ok
        FROM teacher t WHERE t.id = NEW.teacher_id;
    WHEN 'teacher_employment' THEN
        SELECT t.school_id = d.school_id AND t.school_id = y.school_id
            AND NEW.valid_from >= s.starts_on
            AND NEW.valid_from <= s.ends_on
            AND (NEW.valid_to IS NULL OR NEW.valid_to <= s.ends_on)
            AND NEW.valid_from >= d.valid_from
            AND (d.valid_to IS NULL OR COALESCE(NEW.valid_to, s.ends_on) <= d.valid_to)
        INTO context_ok
        FROM teacher t, department d, semester s
        JOIN academic_year y ON y.id = s.academic_year_id
        WHERE t.id = NEW.teacher_id AND d.id = NEW.department_id
          AND s.id = NEW.semester_id;
    WHEN 'manager_scope' THEN
        SELECT u.school_id = y.school_id
            AND NEW.valid_from >= y.starts_on AND NEW.valid_from <= y.ends_on
            AND (NEW.valid_to IS NULL OR NEW.valid_to <= y.ends_on)
        INTO context_ok FROM user_account u, academic_year y
        WHERE u.id = NEW.user_id AND y.id = NEW.academic_year_id;
    WHEN 'class_subject_applicability' THEN
        SELECT c.grade_id = sc.grade_id AND c.academic_year_id = s.academic_year_id
        INTO context_ok FROM school_class c, round_subject_scope sc
        JOIN assignment_round r ON r.id = sc.round_id
        JOIN semester s ON s.id = r.semester_id
        WHERE c.id = NEW.class_id AND sc.id = NEW.scope_id;
    WHEN 'teaching_demand' THEN
        SELECT c.academic_year_id = s.academic_year_id
        INTO context_ok FROM school_class c, semester s
        WHERE c.id = NEW.class_id AND s.id = NEW.semester_id;
    WHEN 'plan_version' THEN
        SELECT p.round_id = sn.round_id INTO context_ok
        FROM assignment_plan p, input_snapshot sn
        WHERE p.id = NEW.plan_id AND sn.id = NEW.input_snapshot_id;
    WHEN 'plan_demand' THEN
        SELECT d.semester_id = r.semester_id AND EXISTS (
            SELECT 1 FROM round_subject_scope sc
            JOIN school_class c ON c.grade_id = sc.grade_id
            JOIN class_subject_applicability a ON a.scope_id = sc.id AND a.class_id = c.id
            WHERE sc.round_id = r.id AND sc.subject_id = d.subject_id
              AND c.id = d.class_id AND a.status = 'APPLICABLE'
        ) INTO context_ok
        FROM plan_version v JOIN assignment_plan p ON p.id = v.plan_id
        JOIN assignment_round r ON r.id = p.round_id
        CROSS JOIN teaching_demand d
        WHERE v.id = NEW.plan_version_id AND d.id = NEW.demand_id;
    WHEN 'calculation_period' THEN
        SELECT NEW.starts_on >= s.starts_on AND NEW.ends_on <= s.ends_on
        INTO context_ok FROM semester s WHERE s.id = NEW.semester_id;
    WHEN 'teacher_duty', 'teacher_reduction' THEN
        SELECT t.school_id = y.school_id
            AND NEW.valid_from >= s.starts_on AND NEW.valid_from <= s.ends_on
            AND (NEW.valid_to IS NULL OR NEW.valid_to <= s.ends_on)
        INTO context_ok FROM teacher t, semester s
        JOIN academic_year y ON y.id = s.academic_year_id
        WHERE t.id = NEW.teacher_id AND s.id = NEW.semester_id;
        IF TG_TABLE_NAME = 'teacher_duty' THEN
            IF NEW.class_id IS NOT NULL THEN
                context_ok := context_ok AND EXISTS (
                    SELECT 1 FROM school_class c JOIN semester s ON s.academic_year_id = c.academic_year_id
                    WHERE c.id = NEW.class_id AND s.id = NEW.semester_id
                );
            END IF;
        END IF;
    WHEN 'converted_activity', 'teacher_period_workload' THEN
        SELECT t.school_id = y.school_id INTO context_ok
        FROM teacher t, calculation_period cp
        JOIN semester s ON s.id = cp.semester_id
        JOIN academic_year y ON y.id = s.academic_year_id
        WHERE t.id = NEW.teacher_id AND cp.id = NEW.calculation_period_id;
    WHEN 'fund_allocation' THEN
        SELECT ctx.semester_id = td.semester_id
            AND NEW.valid_from >= td.valid_from
            AND NEW.valid_from <= s.ends_on
            AND COALESCE(NEW.valid_to, s.ends_on) <= COALESCE(td.valid_to, s.ends_on)
        INTO context_ok FROM school_fund f
        JOIN school_context ctx ON ctx.id = f.school_context_id
        JOIN semester s ON s.id = ctx.semester_id
        CROSS JOIN teacher_duty td
        WHERE f.id = NEW.school_fund_id AND td.id = NEW.teacher_duty_id;
    ELSE
        RAISE EXCEPTION 'Unsupported context table: %', TG_TABLE_NAME;
    END CASE;
    IF context_ok IS DISTINCT FROM TRUE THEN
        RAISE EXCEPTION 'Invalid school/semester/scope/date context in % (id=%)',
            TG_TABLE_NAME, NEW.id USING ERRCODE = '23514';
    END IF;
    RETURN NEW;
END;
$$;

