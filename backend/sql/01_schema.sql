CREATE FUNCTION tass_teacher_eligible(p_teacher BIGINT,p_demand BIGINT) RETURNS BOOLEAN
LANGUAGE sql STABLE AS $$
 SELECT COALESCE(t.school_id=y.school_id
  AND (SELECT range_agg(daterange(e.valid_from,COALESCE(e.valid_to,se.ends_on),'[]'))
       FROM teacher_employment e WHERE e.teacher_id=t.id AND e.semester_id=se.id
       AND e.employment_status='TEACHING') @> daterange(d.valid_from,d.valid_to,'[]')
  AND (SELECT range_agg(daterange(q.valid_from,q.valid_to,'[]')) FROM teaching_qualification q
       WHERE q.teacher_id=t.id AND q.subject_id=d.subject_id AND q.education_level_id=g.education_level_id
       AND q.verification_status='VERIFIED') @> daterange(d.valid_from,d.valid_to,'[]'),FALSE)
 FROM teacher t CROSS JOIN teaching_demand d JOIN semester se ON se.id=d.semester_id
 JOIN academic_year y ON y.id=se.academic_year_id JOIN school_class c ON c.id=d.class_id
 JOIN grade g ON g.id=c.grade_id WHERE t.id=p_teacher AND d.id=p_demand;
$$;

CREATE FUNCTION tass_check_context() RETURNS TRIGGER LANGUAGE plpgsql AS $$
DECLARE ok BOOLEAN:=TRUE; b NUMERIC; expected_b NUMERIC;
BEGIN
 CASE TG_TABLE_NAME
 WHEN 'semester' THEN
  SELECT NEW.starts_on>=y.starts_on AND NEW.ends_on<=y.ends_on INTO ok FROM academic_year y WHERE y.id=NEW.academic_year_id;
 WHEN 'user_account' THEN
  IF NEW.teacher_id IS NOT NULL THEN SELECT t.school_id=NEW.school_id INTO ok FROM teacher t WHERE t.id=NEW.teacher_id; END IF;
 WHEN 'teacher_employment' THEN
  SELECT t.school_id=d.school_id AND t.school_id=y.school_id
   AND NEW.valid_from>=s.starts_on AND NEW.valid_from<=s.ends_on
   AND COALESCE(NEW.valid_to,s.ends_on)<=s.ends_on AND NEW.valid_from>=d.valid_from
   AND (d.valid_to IS NULL OR COALESCE(NEW.valid_to,s.ends_on)<=d.valid_to)
  INTO ok FROM teacher t,department d,semester s JOIN academic_year y ON y.id=s.academic_year_id
  WHERE t.id=NEW.teacher_id AND d.id=NEW.department_id AND s.id=NEW.semester_id;
 WHEN 'manager_scope' THEN
  SELECT u.school_id=y.school_id AND NEW.valid_from>=y.starts_on AND NEW.valid_from<=y.ends_on
   AND COALESCE(NEW.valid_to,y.ends_on)<=y.ends_on INTO ok FROM user_account u,academic_year y
  WHERE u.id=NEW.user_id AND y.id=NEW.academic_year_id;
 WHEN 'round_subject_scope' THEN
  SELECT s.valid_from<=se.ends_on AND (s.valid_to IS NULL OR s.valid_to>=se.starts_on)
   INTO ok FROM assignment_round r JOIN semester se ON se.id=r.semester_id CROSS JOIN subject s
   WHERE r.id=NEW.round_id AND s.id=NEW.subject_id;
 WHEN 'class_subject_applicability' THEN
  SELECT c.grade_id=sc.grade_id AND c.academic_year_id=se.academic_year_id
   INTO ok FROM school_class c,round_subject_scope sc JOIN assignment_round r ON r.id=sc.round_id
   JOIN semester se ON se.id=r.semester_id WHERE c.id=NEW.class_id AND sc.id=NEW.scope_id;
  IF NEW.status='NOT_APPLICABLE' AND EXISTS (
   SELECT 1 FROM teaching_demand d JOIN round_subject_scope sc ON sc.subject_id=d.subject_id
   JOIN assignment_round r ON r.id=sc.round_id
   WHERE sc.id=NEW.scope_id AND d.class_id=NEW.class_id AND d.semester_id=r.semester_id AND d.status='ACTIVE'
  ) THEN ok:=FALSE; END IF;
 WHEN 'teaching_demand' THEN
  SELECT c.academic_year_id=se.academic_year_id AND NEW.valid_from>=se.starts_on AND NEW.valid_to<=se.ends_on
   AND NEW.valid_from>=sub.valid_from AND (sub.valid_to IS NULL OR NEW.valid_to<=sub.valid_to)
   INTO ok FROM school_class c,semester se,subject sub
   WHERE c.id=NEW.class_id AND se.id=NEW.semester_id AND sub.id=NEW.subject_id;
  IF NEW.status='ACTIVE' AND EXISTS (
   SELECT 1 FROM class_subject_applicability a JOIN round_subject_scope sc ON sc.id=a.scope_id
   JOIN assignment_round r ON r.id=sc.round_id WHERE a.class_id=NEW.class_id
    AND sc.subject_id=NEW.subject_id AND r.semester_id=NEW.semester_id AND a.status='NOT_APPLICABLE'
  ) THEN ok:=FALSE; END IF;
 WHEN 'required_demand_component' THEN
  SELECT a.status='APPLICABLE' AND NEW.valid_from>=se.starts_on AND NEW.valid_to<=se.ends_on
   INTO ok FROM class_subject_applicability a JOIN round_subject_scope sc ON sc.id=a.scope_id
   JOIN assignment_round r ON r.id=sc.round_id JOIN semester se ON se.id=r.semester_id
   WHERE a.id=NEW.applicability_id;
  IF NEW.demand_id IS NOT NULL THEN
   ok:=ok AND EXISTS (SELECT 1 FROM teaching_demand d,class_subject_applicability a
     JOIN round_subject_scope sc ON sc.id=a.scope_id JOIN assignment_round r ON r.id=sc.round_id
     WHERE a.id=NEW.applicability_id AND d.id=NEW.demand_id AND d.class_id=a.class_id
      AND d.subject_id=sc.subject_id AND d.semester_id=r.semester_id AND d.demand_type=NEW.demand_type
      AND d.valid_from=NEW.valid_from AND d.valid_to=NEW.valid_to AND d.status='ACTIVE');
  END IF;
 WHEN 'teaching_experience' THEN
  IF NEW.source_import_id IS NOT NULL THEN
   SELECT t.school_id=i.school_id INTO ok FROM teacher t,source_import i
    WHERE t.id=NEW.teacher_id AND i.id=NEW.source_import_id;
  END IF;
 WHEN 'teaching_history' THEN
  SELECT se.academic_year_id=NEW.academic_year_id AND c.academic_year_id=NEW.academic_year_id
   AND NEW.taught_from>=se.starts_on AND NEW.taught_to<=se.ends_on INTO ok
   FROM semester se,school_class c WHERE se.id=NEW.semester_id AND c.id=NEW.class_id;
  IF NEW.source_plan_demand_id IS NOT NULL THEN
   ok:=ok AND EXISTS (SELECT 1 FROM plan_demand pd JOIN teaching_demand td ON td.id=pd.demand_id
    WHERE pd.id=NEW.source_plan_demand_id AND pd.teacher_id=NEW.teacher_id AND td.class_id=NEW.class_id
     AND td.subject_id=NEW.subject_id AND td.semester_id=NEW.semester_id);
  END IF;
 WHEN 'teacher_workload_basis' THEN
  SELECT t.school_id=y.school_id AND NEW.valid_from>=se.starts_on AND NEW.valid_to<=se.ends_on
   INTO ok FROM teacher t,semester se JOIN academic_year y ON y.id=se.academic_year_id
   WHERE t.id=NEW.teacher_id AND se.id=NEW.semester_id;
  SELECT CASE level_code WHEN 'THCS' THEN 19 WHEN 'THPT' THEN 17 END INTO expected_b
   FROM education_level WHERE id=NEW.education_level_id;
  IF NEW.position_code='TEACHER' AND NEW.verification_status='VERIFIED'
    AND NEW.base_periods_per_week IS DISTINCT FROM expected_b THEN ok:=FALSE; END IF;
  IF NEW.source_import_id IS NOT NULL THEN
   ok:=ok AND EXISTS (SELECT 1 FROM source_import i JOIN teacher t ON t.school_id=i.school_id
     WHERE i.id=NEW.source_import_id AND t.id=NEW.teacher_id);
  END IF;
 WHEN 'plan_version' THEN
  SELECT p.round_id=sn.round_id INTO ok FROM assignment_plan p,input_snapshot sn
   WHERE p.id=NEW.plan_id AND sn.id=NEW.input_snapshot_id;
  IF NEW.source_version_id IS NOT NULL THEN
   ok:=ok AND EXISTS(SELECT 1 FROM plan_version v WHERE v.id=NEW.source_version_id
    AND v.plan_id=NEW.plan_id AND v.version_no<NEW.version_no);
  END IF;
 WHEN 'validation_run','solver_run' THEN
  SELECT p.round_id=sn.round_id INTO ok FROM plan_version v JOIN assignment_plan p ON p.id=v.plan_id
   CROSS JOIN input_snapshot sn WHERE v.id=NEW.plan_version_id AND sn.id=NEW.input_snapshot_id;
 WHEN 'calculation_period' THEN
  SELECT NEW.starts_on>=s.starts_on AND NEW.ends_on<=s.ends_on INTO ok FROM semester s WHERE s.id=NEW.semester_id;
 WHEN 'teacher_duty','teacher_reduction' THEN
  SELECT t.school_id=y.school_id AND NEW.valid_from>=s.starts_on AND NEW.valid_from<=s.ends_on
   AND COALESCE(NEW.valid_to,s.ends_on)<=s.ends_on INTO ok FROM teacher t,semester s
   JOIN academic_year y ON y.id=s.academic_year_id WHERE t.id=NEW.teacher_id AND s.id=NEW.semester_id;
  IF TG_TABLE_NAME='teacher_duty' THEN
   IF NEW.class_id IS NOT NULL THEN
   ok:=ok AND EXISTS(SELECT 1 FROM school_class c JOIN semester se ON se.academic_year_id=c.academic_year_id
    WHERE c.id=NEW.class_id AND se.id=NEW.semester_id);
   END IF;
  END IF;
 WHEN 'converted_activity','teacher_period_workload' THEN
  SELECT t.school_id=y.school_id INTO ok FROM teacher t,calculation_period cp
   JOIN semester s ON s.id=cp.semester_id JOIN academic_year y ON y.id=s.academic_year_id
   WHERE t.id=NEW.teacher_id AND cp.id=NEW.calculation_period_id;
 WHEN 'fund_allocation' THEN
  SELECT ctx.semester_id=td.semester_id AND NEW.valid_from>=td.valid_from
   AND COALESCE(NEW.valid_to,se.ends_on)<=COALESCE(td.valid_to,se.ends_on)
   INTO ok FROM school_fund sf JOIN school_context ctx ON ctx.id=sf.school_context_id
   JOIN semester se ON se.id=ctx.semester_id CROSS JOIN teacher_duty td
   WHERE sf.id=NEW.school_fund_id AND td.id=NEW.teacher_duty_id;
 WHEN 'source_import' THEN
  SELECT u.school_id=NEW.school_id INTO ok FROM user_account u WHERE u.id=NEW.imported_by;
 WHEN 'teacher_alias' THEN
  SELECT t.school_id=i.school_id INTO ok FROM teacher t,source_import i
   WHERE t.id=NEW.teacher_id AND i.id=NEW.source_import_id;
 WHEN 'class_alias' THEN
  SELECT y.school_id=i.school_id INTO ok FROM school_class c JOIN academic_year y ON y.id=c.academic_year_id
   CROSS JOIN source_import i WHERE c.id=NEW.class_id AND i.id=NEW.source_import_id;
 WHEN 'subject_alias' THEN
  ok:=EXISTS(SELECT 1 FROM source_import WHERE id=NEW.source_import_id);
 END CASE;
 IF ok IS DISTINCT FROM TRUE THEN
  RAISE EXCEPTION 'Invalid school/year/semester/subject/period context in % id=%',TG_TABLE_NAME,NEW.id USING ERRCODE='23514';
 END IF;
 RETURN NEW;
END;
$$;
DO $$
DECLARE t TEXT;
BEGIN
 FOREACH t IN ARRAY ARRAY['semester','user_account','teacher_employment','manager_scope','round_subject_scope',
 'class_subject_applicability','teaching_demand','required_demand_component','teaching_experience','teaching_history',
 'teacher_workload_basis','plan_version','validation_run','solver_run','calculation_period','teacher_duty',
