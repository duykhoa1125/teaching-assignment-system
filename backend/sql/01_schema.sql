-- 20. teaching_demand
CREATE TABLE teaching_demand (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    semester_id BIGINT NOT NULL REFERENCES semester(id),
    class_id BIGINT NOT NULL REFERENCES school_class(id),
    subject_id BIGINT NOT NULL REFERENCES subject(id),
    periods_per_week NUMERIC(5,2) NOT NULL CHECK (periods_per_week > 0),
    status VARCHAR(40) NOT NULL CHECK (btrim(status) <> ''),
