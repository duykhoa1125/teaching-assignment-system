    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    demand_type VARCHAR(30) NOT NULL CHECK (demand_type IN ('STANDARD','SPECIALIZED_TOPIC')),
    UNIQUE (semester_id, class_id, subject_id, demand_type)
);

-- 21. optimization_config
