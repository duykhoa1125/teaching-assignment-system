-- 17. assignment_round
CREATE TABLE assignment_round (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    semester_id BIGINT NOT NULL REFERENCES semester(id),
    round_code VARCHAR(50) NOT NULL,
    status VARCHAR(40) NOT NULL CHECK (btrim(status) <> ''),
    scope_confirmed_by BIGINT REFERENCES user_account(id),
    scope_confirmed_at TIMESTAMPTZ,
    opens_at TIMESTAMPTZ,
    closes_at TIMESTAMPTZ,
    UNIQUE (semester_id, round_code),
    CHECK (opens_at IS NULL OR closes_at IS NULL OR closes_at >= opens_at)
);

-- 18. round_subject_scope
