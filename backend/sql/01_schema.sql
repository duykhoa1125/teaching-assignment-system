-- Chi ho tro nguon OUTSIDE_SCOPE_WEEKLY va converted_activity.unit=PERIOD_PER_WEEK.
-- Don vi khac can normalization o service; function tra NULL thay vi tu quy doi.
CREATE FUNCTION tass_snapshot_weekly_load(p_version BIGINT,p_on DATE)
RETURNS TABLE(teacher_id BIGINT,teacher_code TEXT,is_teaching BOOLEAN,b NUMERIC,f NUMERIC,a NUMERIC,
 c NUMERIC,r NUMERIC,t NUMERIC,delta NUMERIC,weekly_complete BOOLEAN)
LANGUAGE sql STABLE AS $$
WITH src AS (SELECT sn.payload_json j FROM plan_version v JOIN input_snapshot sn ON sn.id=v.input_snapshot_id WHERE v.id=p_version),
period AS (SELECT CASE WHEN count(*)=1 THEN min((z->>'id')::BIGINT) END id FROM src,
 LATERAL jsonb_array_elements(j->'calculation_periods') z WHERE p_on BETWEEN (z->>'starts_on')::DATE AND (z->>'ends_on')::DATE),
base AS (
 SELECT (te->>'id')::BIGINT tid,te->>'teacher_code' code,
 EXISTS(SELECT 1 FROM jsonb_array_elements(j->'employment') e WHERE (e->>'teacher_id')::BIGINT=(te->>'id')::BIGINT
 AND e->>'employment_status'='TEACHING' AND p_on >= (e->>'valid_from')::DATE
 AND p_on<=COALESCE((e->>'valid_to')::DATE,(j#>>'{semester,ends_on}')::DATE)) teaching,
 (SELECT (z->>'base_periods_per_week')::NUMERIC FROM jsonb_array_elements(j->'workload_basis') z
  WHERE (z->>'teacher_id')::BIGINT=(te->>'id')::BIGINT AND z->>'verification_status'='VERIFIED'
   AND p_on BETWEEN (z->>'valid_from')::DATE AND (z->>'valid_to')::DATE) bv,
 (SELECT (z->>'teaching_periods')::NUMERIC FROM jsonb_array_elements(j->'period_workloads') z
  WHERE (z->>'teacher_id')::BIGINT=(te->>'id')::BIGINT AND (z->>'calculation_period_id')::BIGINT=period.id
   AND z->>'record_type'='OUTSIDE_SCOPE_WEEKLY' AND z->>'verification_status'='VERIFIED') fv,
 COALESCE((SELECT sum(pd.periods_per_week_snapshot) FROM plan_demand pd
  JOIN LATERAL jsonb_array_elements(j->'demands') dd ON (dd->>'id')::BIGINT=pd.demand_id
  WHERE pd.plan_version_id=p_version AND pd.teacher_id=(te->>'id')::BIGINT
   AND p_on BETWEEN (dd->>'valid_from')::DATE AND (dd->>'valid_to')::DATE),0) av,
 CASE WHEN (j->>'weekly_inputs_confirmed')::BOOLEAN AND NOT EXISTS(
  SELECT 1 FROM jsonb_array_elements(j->'converted_activities') z WHERE (z->>'teacher_id')::BIGINT=(te->>'id')::BIGINT
  AND (z->>'calculation_period_id')::BIGINT=period.id AND (z->>'include_in_workload')::BOOLEAN
  AND (z->>'verification_status'<>'VERIFIED' OR z->>'converted_periods' IS NULL OR z->>'original_unit'<>'PERIOD_PER_WEEK'))
 THEN COALESCE((SELECT sum((z->>'converted_periods')::NUMERIC) FROM jsonb_array_elements(j->'converted_activities') z
  WHERE (z->>'teacher_id')::BIGINT=(te->>'id')::BIGINT AND (z->>'calculation_period_id')::BIGINT=period.id
   AND (z->>'include_in_workload')::BOOLEAN AND z->>'verification_status'='VERIFIED'),0) END cv,
 CASE WHEN (j->>'weekly_inputs_confirmed')::BOOLEAN AND NOT EXISTS(
  SELECT 1 FROM (SELECT x FROM jsonb_array_elements(j->'duties') x UNION ALL SELECT x FROM jsonb_array_elements(j->'reductions') x) z
  WHERE (x->>'teacher_id')::BIGINT=(te->>'id')::BIGINT AND p_on>=(x->>'valid_from')::DATE
   AND p_on<=COALESCE((x->>'valid_to')::DATE,(j#>>'{semester,ends_on}')::DATE)
   AND (x->>'verification_status'<>'VERIFIED' OR x->>'reduction_value' IS NULL))
 THEN COALESCE((SELECT sum((x->>'reduction_value')::NUMERIC)
  FROM (SELECT x FROM jsonb_array_elements(j->'duties') x UNION ALL SELECT x FROM jsonb_array_elements(j->'reductions') x) z
  WHERE (x->>'teacher_id')::BIGINT=(te->>'id')::BIGINT AND x->>'verification_status'='VERIFIED'
   AND p_on>=(x->>'valid_from')::DATE AND p_on<=COALESCE((x->>'valid_to')::DATE,(j#>>'{semester,ends_on}')::DATE)),0) END rv
 FROM src CROSS JOIN period CROSS JOIN LATERAL jsonb_array_elements(j->'teachers') te
)
SELECT tid,code,teaching,bv,fv,av,cv,rv,fv+av+cv+rv,
 CASE WHEN teaching THEN fv+av+cv+rv-bv END,
 bv IS NOT NULL AND fv IS NOT NULL AND cv IS NOT NULL AND rv IS NOT NULL FROM base;
$$;
