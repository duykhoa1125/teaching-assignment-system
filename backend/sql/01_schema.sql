-- 01. school
CREATE TABLE school (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    school_code VARCHAR(50) NOT NULL,
    name VARCHAR(255) NOT NULL,
    status VARCHAR(40) NOT NULL CHECK (btrim(status) <> ''),
    UNIQUE (school_code)
);

-- 02. department
CREATE TABLE department (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    school_id BIGINT NOT NULL REFERENCES school(id),
    department_code VARCHAR(50) NOT NULL,
    name VARCHAR(255) NOT NULL,
    valid_from DATE NOT NULL,
    valid_to DATE,
    UNIQUE (school_id, department_code),
    CHECK (valid_to IS NULL OR valid_to >= valid_from)
);

-- 03. academic_year
CREATE TABLE academic_year (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    school_id BIGINT NOT NULL REFERENCES school(id),
    year_code VARCHAR(30) NOT NULL,
    starts_on DATE NOT NULL,
    ends_on DATE NOT NULL,
    UNIQUE (school_id, year_code),
    CHECK (ends_on >= starts_on)
);

-- 04. semester
CREATE TABLE semester (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    academic_year_id BIGINT NOT NULL REFERENCES academic_year(id),
    semester_no SMALLINT NOT NULL CHECK (semester_no > 0),
    starts_on DATE NOT NULL,
    ends_on DATE NOT NULL,
    UNIQUE (academic_year_id, semester_no),
    CHECK (ends_on >= starts_on)
);

-- 05. education_level
CREATE TABLE education_level (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    level_code VARCHAR(30) NOT NULL,
    name VARCHAR(150) NOT NULL,
    UNIQUE (level_code)
);

-- 06. grade
CREATE TABLE grade (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    education_level_id BIGINT NOT NULL REFERENCES education_level(id),
    grade_code VARCHAR(30) NOT NULL,
    name VARCHAR(150) NOT NULL,
    UNIQUE (education_level_id, grade_code)
);

-- 07. school_class
CREATE TABLE school_class (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    academic_year_id BIGINT NOT NULL REFERENCES academic_year(id),
    grade_id BIGINT NOT NULL REFERENCES grade(id),
    class_code VARCHAR(50) NOT NULL,
    status VARCHAR(40) NOT NULL CHECK (btrim(status) <> ''),
    UNIQUE (academic_year_id, class_code)
);

-- 08. subject
CREATE TABLE subject (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    subject_code VARCHAR(50) NOT NULL,
    name VARCHAR(255) NOT NULL,
    valid_from DATE NOT NULL,
    valid_to DATE,
    UNIQUE (subject_code),
    CHECK (valid_to IS NULL OR valid_to >= valid_from)
);

-- 09. teacher
CREATE TABLE teacher (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    school_id BIGINT NOT NULL REFERENCES school(id),
    teacher_code VARCHAR(50) NOT NULL,
    full_name VARCHAR(255) NOT NULL,
    UNIQUE (school_id, teacher_code)
);

-- 10. user_account
CREATE TABLE user_account (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    school_id BIGINT NOT NULL REFERENCES school(id),
    teacher_id BIGINT REFERENCES teacher(id),
    login_name VARCHAR(100) NOT NULL,
    credential_hash TEXT NOT NULL,
    status VARCHAR(40) NOT NULL CHECK (btrim(status) <> ''),
    UNIQUE (login_name),
