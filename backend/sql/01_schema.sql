CREATE VIEW v_tass_preparation_issues AS
WITH pairs AS (
 SELECT r.id round_id,r.semester_id,sc.id scope_id,sc.subject_id,c.id class_id,a.id applicability_id,
 a.status,a.confirmed_by,a.components_confirmed_by
 FROM assignment_round r JOIN semester se ON se.id=r.semester_id
 JOIN round_subject_scope sc ON sc.round_id=r.id
 JOIN school_class c ON c.grade_id=sc.grade_id AND c.academic_year_id=se.academic_year_id
 LEFT JOIN class_subject_applicability a ON a.scope_id=sc.id AND a.class_id=c.id
)
SELECT r.id round_id,'ROUND_SCOPE_UNCONFIRMED'::TEXT issue,r.id record_id
 FROM assignment_round r WHERE r.scope_confirmed_by IS NULL OR r.scope_confirmed_at IS NULL
UNION ALL
SELECT sc.round_id,'SCOPE_UNCONFIRMED',sc.id FROM round_subject_scope sc WHERE confirmed_by IS NULL OR confirmed_at IS NULL
UNION ALL
SELECT p.round_id,CASE WHEN p.applicability_id IS NULL THEN 'MISSING_APPLICABILITY'
 WHEN p.status='UNDETERMINED' THEN 'UNDETERMINED'
 WHEN p.confirmed_by IS NULL THEN 'APPLICABILITY_UNCONFIRMED' ELSE 'REQUIRED_SET_UNCONFIRMED' END,p.class_id
 FROM pairs p WHERE p.applicability_id IS NULL OR p.status='UNDETERMINED' OR p.confirmed_by IS NULL
 OR (p.status='APPLICABLE' AND p.components_confirmed_by IS NULL)
UNION ALL
SELECT p.round_id,'EMPTY_REQUIRED_SET',p.applicability_id FROM pairs p WHERE p.status='APPLICABLE'
 AND NOT EXISTS(SELECT 1 FROM required_demand_component c WHERE c.applicability_id=p.applicability_id)
UNION ALL
SELECT p.round_id,'MISSING_OR_INVALID_REQUIRED_DEMAND',c.id FROM pairs p
 JOIN required_demand_component c ON c.applicability_id=p.applicability_id
 LEFT JOIN teaching_demand d ON d.id=c.demand_id
 WHERE p.status='APPLICABLE' AND (c.confirmed_by IS NULL OR c.confirmed_at IS NULL OR d.id IS NULL
 OR d.status<>'ACTIVE' OR d.class_id<>p.class_id OR d.subject_id<>p.subject_id OR d.semester_id<>p.semester_id
 OR d.demand_type<>c.demand_type OR d.valid_from<>c.valid_from OR d.valid_to<>c.valid_to)
UNION ALL
SELECT p.round_id,'ACTIVE_DEMAND_NOT_IN_REQUIRED_SET',d.id FROM pairs p
 JOIN teaching_demand d ON d.class_id=p.class_id AND d.subject_id=p.subject_id AND d.semester_id=p.semester_id
 WHERE p.status='APPLICABLE' AND d.status='ACTIVE'
 AND NOT EXISTS(SELECT 1 FROM required_demand_component c WHERE c.applicability_id=p.applicability_id AND c.demand_id=d.id)
UNION ALL
SELECT p.round_id,'DEMAND_ON_NOT_APPLICABLE',d.id FROM pairs p
 JOIN teaching_demand d ON d.class_id=p.class_id AND d.subject_id=p.subject_id AND d.semester_id=p.semester_id
 WHERE p.status='NOT_APPLICABLE' AND d.status='ACTIVE';

